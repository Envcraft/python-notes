# Level 1 - Topic 1: Syntax & Variables
# Python syntax basics and variable assignment

# Variables - no need to declare type
name = "Alice"
age = 25
height = 5.6
is_student = True

print(name)       # Alice
print(age)        # 25
print(height)     # 5.6
print(is_student) # True

# Multiple assignment
x, y, z = 1, 2, 3
print(x, y, z)   # 1 2 3

# Python is case-sensitive
Name = "Bob"
print(name)  # Alice
print(Name)  # Bob
